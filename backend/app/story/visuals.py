"""Story backgrounds: where the picture behind the narration comes from.

A `VisualSource` contributes FFmpeg inputs and a filter chain that produces the
[bg] stream: a 1080x1920, 30 fps video exactly as long as the Short. v1 has one
kind, `LoopBackground` (any video, center-cropped to 9:16, looped or trimmed and
slightly darkened so captions stay readable). v2 can add a source that builds one
AI image per scene from `visual_description` with slow pan/zoom, using the same
interface: `filter()` receives the scene timeline.

Background choices are stored in the story document as references:
  {"kind": "bundled", "id": "midnight"}     generated by FFmpeg, no stock footage
  {"kind": "folder", "name": "rain.mp4"}    a file in STORY_BACKGROUNDS_DIR
  {"kind": "library", "projectId": "prj_…"} one of the creator's uploaded videos
  {"kind": "ai", "id": "flux"}              one AI picture per scene (v2), with
                                             pan/zoom: SceneImagesBackground
"""

import logging
import subprocess
from abc import ABC, abstractmethod
from dataclasses import dataclass
from itertools import pairwise
from pathlib import Path

from sqlalchemy import select

from ..db_models import ProjectRecord, UploadRecord
from ..errors import ApiError
from ..renderer import fill_filter
from . import cache

logger = logging.getLogger(__name__)

WIDTH, HEIGHT, FPS = 1080, 1920, 30
VIDEO_EXTENSIONS = {".mp4", ".mov", ".m4v", ".webm", ".mkv"}
# Slightly darker, slightly less saturated: white captions stay readable on any clip.
DARKEN = "eq=brightness=-0.06:gamma=0.85:saturation=0.9"


@dataclass(frozen=True)
class Bundled:
    id: str
    label: str
    colors: tuple[str, str, str]


# Original, license-free loops generated on first use: slow drifting gradients with
# film grain, played forward then backward so the loop is seamless.
BUNDLED = {
    b.id: b
    for b in [
        Bundled("midnight", "Midnight", ("0x0b1026", "0x2a1b4a", "0x101a3a")),
        Bundled("ember", "Ember", ("0x2b0d05", "0x6b2a0b", "0x1a0a05")),
        Bundled("deep-sea", "Deep sea", ("0x041c2c", "0x0b3d5c", "0x06283d")),
        Bundled("forest", "Forest", ("0x07160d", "0x1d3b23", "0x0c2416")),
        Bundled("dusk", "Dusk", ("0x2a1030", "0x5c2a3e", "0x1a1030")),
    ]
}
BUNDLED_VERSION = "1"
HALF_LOOP = 6  # seconds forward, then the same backward


class VisualSource(ABC):
    @abstractmethod
    def inputs(self) -> list[str]:
        """FFmpeg input arguments (one or more -i)."""

    @abstractmethod
    def filter(self, first_input: int, duration: float, timeline: list[dict]) -> str:
        """A filter chain ending in [bg]: WIDTH x HEIGHT, FPS, exactly `duration`."""


class LoopBackground(VisualSource):
    def __init__(self, path: Path, start: float = 0.0, darken: bool = True):
        # Bundled loops are made dark already; only arbitrary clips are darkened.
        self.path, self.start, self.darken = Path(path), max(0.0, start), darken

    def inputs(self):
        # Loop forever and cut to length in the filter: short clips repeat, long ones trim.
        return ["-stream_loop", "-1", "-ss", f"{self.start:.3f}", "-i", str(self.path)]

    def filter(self, first_input, duration, timeline):
        return (
            f"[{first_input}:v:0]{fill_filter(WIDTH, HEIGHT)},fps={FPS},"
            f"trim=duration={duration:.3f},setpts=PTS-STARTPTS,"
            f"{DARKEN + ',' if self.darken else ''}format=yuv420p[bg]"
        )


# Pan/zoom ("Ken Burns") motions, cycled scene by scene. {p} runs 0 -> 1 over the shot.
MOTIONS = [
    ("1+0.12*{p}", "iw/2-(iw/zoom/2)", "ih/2-(ih/zoom/2)"),  # slow push in
    ("1.12-0.12*{p}", "iw/2-(iw/zoom/2)", "ih/2-(ih/zoom/2)"),  # slow pull out
    ("1.1", "(iw-iw/zoom)*{p}", "ih/2-(ih/zoom/2)"),  # drift right
    ("1.1", "iw/2-(iw/zoom/2)", "(ih-ih/zoom)*(1-{p})"),  # drift up
]
OVERSCAN = 1.5  # zoom from a larger frame so the motion stays smooth
CROSSFADE = 0.5


class SceneImagesBackground(VisualSource):
    """One still per scene with slow pan/zoom, crossfading exactly at scene starts.

    Shot k runs from scene k's start to scene k+1's start (pauses included); the
    last shot runs to the end of the Short. Each shot except the last is extended by
    the crossfade, so the chained xfades start at every scene start and the total
    length is exactly the Short's duration.
    """

    def __init__(self, images: list[Path]):
        self.images = [Path(p) for p in images]

    def inputs(self):
        return [arg for path in self.images for arg in ("-i", str(path))]

    def filter(self, first_input, duration, timeline):
        starts = [0.0] + [float(scene["start"]) for scene in timeline[1 : len(self.images)]]
        gaps = [b - a for a, b in pairwise(starts)] + [duration - starts[-1]]
        fade = min([CROSSFADE] + [gap / 2 for gap in gaps if gap > 0])
        width, height = round(WIDTH * OVERSCAN), round(HEIGHT * OVERSCAN)
        chains, labels = [], []
        for k, gap in enumerate(gaps):
            seconds = gap + (fade if k < len(gaps) - 1 else 0)
            frames = max(1, round(seconds * FPS))
            zoom, x, y = (expr.format(p=f"(on/{frames})") for expr in MOTIONS[k % len(MOTIONS)])
            chains.append(
                f"[{first_input + k}:v:0]scale={width}:{height}:force_original_aspect_ratio=increase,"
                f"crop={width}:{height},setsar=1,"
                f"zoompan=z='{zoom}':x='{x}':y='{y}':d={frames}:s={WIDTH}x{HEIGHT}:fps={FPS},"
                f"trim=end_frame={frames},setpts=PTS-STARTPTS,fps={FPS},format=yuv420p[s{k}]"
            )
            labels.append(f"[s{k}]")
        current = labels[0]
        for k in range(1, len(labels)):
            chains.append(
                f"{current}{labels[k]}xfade=transition=fade:duration={fade:.3f}"
                f":offset={starts[k]:.3f}[x{k}]"
            )
            current = f"[x{k}]"
        chains.append(
            f"{current}trim=duration={duration:.3f},setpts=PTS-STARTPTS,{DARKEN},format=yuv420p[bg]"
        )
        return ";".join(chains)


def backgrounds_dir(settings) -> Path:
    configured = settings.story_backgrounds_dir
    return (
        Path(configured).expanduser()
        if configured
        else settings.media_dir / "story-library" / "backgrounds"
    )


def folder_files(directory: Path, extensions: set[str]) -> list[Path]:
    if not directory.is_dir():
        return []
    return sorted(
        (p for p in directory.iterdir() if p.is_file() and p.suffix.lower() in extensions),
        key=lambda p: p.name.lower(),
    )


def bundled_file(settings, ffmpeg: str, background: Bundled) -> Path:
    """Generate (once) and cache a bundled loop."""
    key = {"bundled": background.id, "version": BUNDLED_VERSION, "colors": background.colors}
    path = cache.file_path(settings.media_dir, "backgrounds", key, ".mp4")
    if path.is_file():
        cache.touch(path)
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    c0, c1, c2 = background.colors
    graph = (
        f"gradients=s=540x960:c0={c0}:c1={c1}:c2={c2}:nb_colors=3:speed=0.02"
        f":d={HALF_LOOP}:r={FPS},scale={WIDTH}:{HEIGHT}:flags=bicubic,"
        "noise=alls=5:allf=u,split[f][b];[b]reverse[r];[f][r]concat=n=2:v=1:a=0,format=yuv420p"
    )
    temporary = path.with_suffix(".tmp.mp4")
    command = [ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", graph]
    command += ["-c:v", "libx264", "-preset", "veryfast", "-crf", "23", "-an", str(temporary)]
    result = subprocess.run(command, capture_output=True, text=True, timeout=300, check=False)
    if result.returncode or not temporary.is_file():
        temporary.unlink(missing_ok=True)
        logger.warning("Could not generate background %s: %s", background.id, result.stderr[-300:])
        raise ApiError("RENDER_FAILED", "The background could not be prepared.", 500)
    temporary.replace(path)
    logger.info("Generated bundled background %s", background.id)
    return path


def library_uploads(db, user_id: str) -> list[tuple[ProjectRecord, UploadRecord]]:
    rows = db.execute(
        select(ProjectRecord, UploadRecord)
        .join(UploadRecord, UploadRecord.projectId == ProjectRecord.id)
        .where(
            ProjectRecord.userId == user_id,
            ProjectRecord.status != "deleted",
            ProjectRecord.sourceType != "story",
            ProjectRecord.sourceExpired.is_(False),
            UploadRecord.storedName.is_not(None),
        )
        .order_by(ProjectRecord.createdAt.desc())
    )
    return list(rows)


def ai_choices(settings, image_providers: dict) -> list[dict]:
    """AI picture backgrounds for usable image providers (demo only when it is default)."""
    return [
        {"kind": "ai", "id": p.id, "label": "AI pictures", "description": p.label}
        for p in image_providers.values()
        if p.unavailable_reason() is None
        and (p.id != "demo" or settings.story_image_provider == "demo")
    ]


def available(db, settings, user_id: str, image_providers: dict | None = None) -> list[dict]:
    """Everything the background picker can offer this creator."""
    items = ai_choices(settings, image_providers or {})
    items += [
        {"kind": "bundled", "id": b.id, "label": b.label, "description": "Generated loop"}
        for b in BUNDLED.values()
    ]
    items += [
        {"kind": "folder", "id": p.name, "label": p.stem, "description": "Background folder"}
        for p in folder_files(backgrounds_dir(settings), VIDEO_EXTENSIONS)
    ]
    sources = (settings.media_dir / "sources").resolve()
    items += [
        {"kind": "library", "id": project.id, "label": project.name, "description": "Your upload"}
        for project, upload in library_uploads(db, user_id)
        if (sources / upload.storedName).is_file()
    ]
    return items


def reference(choice: dict) -> dict:
    """The reference stored in the story document for a picker item."""
    if choice["kind"] == "bundled":
        return {"kind": "bundled", "id": choice["id"]}
    if choice["kind"] == "folder":
        return {"kind": "folder", "name": choice["id"]}
    if choice["kind"] == "ai":
        return {"kind": "ai", "id": choice["id"]}
    return {"kind": "library", "projectId": choice["id"]}


def resolve(db, settings, user_id: str, ref: dict, ffmpeg: str) -> VisualSource:
    """Turn a stored reference into a source, checking it still exists and is theirs."""
    missing = ApiError(
        "BACKGROUND_UNAVAILABLE", "That background is no longer available. Pick another.", 409
    )
    kind = ref.get("kind")
    if kind == "bundled":
        background = BUNDLED.get(ref.get("id"))
        if not background:
            raise missing
        return LoopBackground(bundled_file(settings, ffmpeg, background), darken=False)
    if kind == "folder":
        directory = backgrounds_dir(settings).resolve()
        path = (directory / str(ref.get("name", ""))).resolve()
        if path.parent != directory or path.suffix.lower() not in VIDEO_EXTENSIONS:
            raise missing
        if not path.is_file():
            raise missing
        return LoopBackground(path)
    if kind == "library":
        sources = (settings.media_dir / "sources").resolve()
        for project, upload in library_uploads(db, user_id):
            if project.id == ref.get("projectId"):
                path = (sources / upload.storedName).resolve()
                if path.parent == sources and path.is_file():
                    return LoopBackground(path, ref.get("start", 0.0))
        raise missing
    raise missing
